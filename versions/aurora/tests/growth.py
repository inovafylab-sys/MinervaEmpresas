"""Funnel-first tabs, accessible details and stage-linked local improvement records."""
import os
from playwright.sync_api import sync_playwright,expect
BASE=os.environ.get('MINERVA_TEST_URL','http://127.0.0.1:4173')
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1040},reduced_motion='reduce')
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(BASE)
 expect(page.locator('.dashboard-tabs [role=tab]')).to_have_count(5)
 expect(page.locator('.dashboard-tabs [aria-selected=true]')).to_have_text('Indicadores')
 expect(page.locator('#route-supervision')).to_have_count(0)
 a=page.locator('.funnel-medicos').bounding_box();z=page.locator('.funnel-pacientes').bounding_box()
 assert abs(a['y']-z['y'])<2 and a['x']+a['width']<=z['x']
 colors=page.locator('.company-funnel').evaluate_all('(els)=>els.map(e=>getComputedStyle(e).getPropertyValue("--funnel-color"))')
 assert colors[0]!=colors[1]
 stage=page.locator('.funnel-medicos [data-stage=accepted]')
 stage.hover();tip=page.locator('#stage-tip-medicos-accepted-')
 expect(tip).to_be_visible();expect(tip).to_contain_text('1 / 2 · 50%')
 stage.click()
 expect(page.locator('#indicator-detail')).to_be_visible()
 expect(page.locator('.company-funnel')).to_have_count(2)
 assert page.url.rstrip('/').endswith('4173')
 expect(page.locator('#indicator-detail-content')).to_contain_text('Sem histórico')
 page.locator('[data-detail-tab=Hipóteses]').click()
 page.locator('#indicator-detail [data-crud-new=hypotheses]').click()
 expect(page.locator('#crud-form [name=metric]')).to_have_value('medicos/accepted')
 for k,v in {'title':'Revisar proposta','hypothesis':'A proposta pode estar pouco clara','solution':'Testar uma apresentação mais objetiva'}.items():page.locator(f'#crud-form [name={k}]').fill(v)
 page.locator('#crud-form button[type=submit]').click()
 expect(page.locator('#indicator-detail-content')).to_contain_text('Revisar proposta')
 page.locator('[data-detail-tab=Experimentos]').click()
 page.locator('#indicator-detail [data-crud-new=experiments]').click()
 for k,v in {'title':'Teste de apresentação','setting':'Texto inicial','hypothesis':'Clareza pode melhorar aceite','control':'Apresentação A','variant':'Apresentação B','population':'Médicos elegíveis; período a definir'}.items():page.locator(f'#crud-form [name={k}]').fill(v)
 page.locator('#crud-form button[type=submit]').click()
 expect(page.locator('#indicator-detail-content')).to_contain_text('Teste de apresentação')
 page.locator('[data-detail-tab="Padrão atual"]').click()
 expect(page.locator('#indicator-detail-content')).to_contain_text('ainda não conectado')
 page.locator('#indicator-detail [data-crud-new=standards]').click()
 for k,v in {'title':'Abordagem atual','setting':'Mensagem de referência demonstrativa','version':'v1'}.items():page.locator(f'#crud-form [name={k}]').fill(v)
 page.locator('#crud-form button[type=submit]').click()
 expect(page.locator('#indicator-detail-content')).to_contain_text('Abordagem atual')
 page.keyboard.press('Escape');expect(page.locator('#indicator-detail')).to_have_count(0)
 page.locator('[data-dashboard-tab=Experimentos]').click();expect(page.locator('#dashboard-content')).to_contain_text('Teste de apresentação')
 page.locator('#growth-metric').select_option('pacientes/paid');expect(page.locator('#dashboard-content')).not_to_contain_text('Teste de apresentação')
 page.reload();page.locator('[data-dashboard-tab=Experimentos]').click();expect(page.locator('#dashboard-content')).to_contain_text('Teste de apresentação')
 page.locator('[data-dashboard-tab="Configuração atual"]').click();expect(page.locator('#dashboard-content')).to_contain_text('Abordagem atual')
 page.locator('[data-dashboard-tab=Indicadores]').click()
 page.set_viewport_size({'width':390,'height':844})
 page.locator('.funnel-pacientes [data-stage=paid]').click()
 detail=page.locator('#indicator-detail').bounding_box();assert detail['x']==0 and detail['width']==390
 page.keyboard.press('Escape');assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
 page.locator('#profile-select').select_option('representante')
 expect(page.locator('.dashboard-tabs')).to_have_count(0)
 assert not errors,errors
 print('PASS: funnel layout/colors, hover rates, stage details, all tabs, stage-linked CRUD persistence, filtering, mobile and role separation')
 b.close()
